def run(bank, html):
    d = parse_rows(extract_rows(html), CFG[bank]); validate(d); return d

def test_tenor():
    cases = {"一個月~未滿三個月": 1, "3至4個月": 3, "一、二個月": 1, "九、十、十一個月": 9, "十一個月": 11,
             "一年~二十三個月": 12, "二年~未滿三年": 24, "三年": 36, "36個月": 36, "13至23個月": 13,
             "1.225": None, "100萬元(含)以下": None, "一般": None}
    for k, v in cases.items():
        assert tenor_months(k) == v, (k, tenor_months(k))

def test_bot():
    d = run("bot", BOT)
    assert d["demand"] == 0.705 and d["demand_savings"] == 0.825
    assert d["time"]["12"] == {"fixed": 1.700, "floating": 1.690}      # 臺銀機動在前
    assert d["time"]["1"]["fixed"] == 1.225 and d["time"]["9"]["fixed"] == 1.580
    assert d["savings"]["12"] == {"fixed": 1.725, "floating": 1.715}
    assert d["savings"]["36"]["fixed"] == 1.785 and d["time"]["36"]["fixed"] == 1.745

